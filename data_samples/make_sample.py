#!/usr/bin/env python3
"""Generates data_samples/sample.xlsx — the input template with example data
and a "Як заповнювати" guidance sheet. Import this into Google Sheets (File
-> Import -> Replace spreadsheet, or File -> Open with Google Sheets) to get
started; share the result with the service account as described in README.md.
"""
