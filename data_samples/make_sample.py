GUIDE.title = "Як заповнювати"
GUIDE.append(["Аркуш", "Що вносити"])
GUIDE["A1"].font = GUIDE["B1"].font = Font(bold=True)
guide_rows = [
    ("Налаштування", "Дата початку семестру (понеділок першого тижня), кількість тижнів, "
     "днів на тиждень, пар на день. По одному рядку \"Параметр\" / \"Значення\"."),
    ("Викладачі", "Прізвище, Ім'я — обов'язкові. «Недоступні дні» — дні тижня через кому "
     "(Пн, Вт, Ср, Чт, Пт), коли викладач повністю недоступний. «Предмети» — через кому."),
    ("Аудиторії", "Номер і Місткість — обов'язкові; Корпус — лише якщо корпусів кілька "
     "(якщо один корпус/заклад, лишіть порожнім, і в «Заняттях» пишіть просто номер, напр. «810»). "
     "«Тип» — лекційна / семінарська / лабораторія / комп'ютерний клас / спортзал / інше."),
    ("Групи", "Код групи — обов'язковий і унікальний, саме на нього посилаються «Заняття»."),
    ("Заняття", "«Викладач» має точно збігатися з «Прізвище Ім'я По-батькові» з аркуша "
     "«Викладачі»; «Група» — з «Код групи» з аркуша «Групи». «Тип розкладу»: "
     "стрічковий (система сама підбирає день/час щотижня, без накладок) / "
     "цикловий (кілька днів поспіль, дату й аудиторію вказуєте самі) / "
     "довільний (довільний список дат, дату й аудиторію вказуєте самі)."),
    ("", "Стрічковий: заповніть «Пар на тиждень» і, за бажанням, «Тижні» "
     "(напр. «1-16», «непарні 1-16»; порожньо = весь семестр). Аудиторію й час "
     "підбере система — вкажіть лише «Тип аудиторії», якщо потрібен конкретний."),
    ("", "Цикловий: «Дата початку», «К-сть днів», «Пари» (напр. «1,2,3») і «Аудиторія» — "
     "точно як записано в аркуші «Аудиторії» (Корпус-Номер, якщо є корпус, інакше просто номер, "
     "напр. «А-305» або «810»)."),
    ("", "Довільний: «Аудиторія» і «Дати та пари» у форматі "
     "«02.09.2026:2; 09.09.2026:2» (дата:номер пари через крапку з комою)."),
    ("", "Після збірки перевірте звіт (вкладка журналу Actions на GitHub): він показує "
     "накладки, незрозумілі посилання й нерозставлені заняття."),
]
for row in guide_rows:
    GUIDE.append(row)
GUIDE.column_dimensions["A"].width = 16
GUIDE.column_dimensions["B"].width = 110

settings = wb.create_sheet("Налаштування")
settings.append(["Параметр", "Значення"])
settings.append(["Дата початку семестру", "2026-09-01"])
settings.append(["Кількість тижнів", 16])
settings.append(["Днів на тиждень", 5])
settings.append(["Пар на день", 6])

teachers = wb.create_sheet("Викладачі")
teachers.append(["Прізвище", "Ім'я", "По батькові", "Ступінь", "Звання", "Посада", "Ставка",
                  "Кафедра", "Факультет", "Предмети", "Недоступні дні"])
teachers.append(["Коваленко", "Олена", "Іванівна", "кандидат наук", "доцент", "доцент", 1.0,
                  "Кафедра програмної інженерії", "Факультет інформатики", "Бази даних, Алгоритми", "Пт"])
teachers.append(["Бондаренко", "Андрій", "Петрович", "немає", "немає", "асистент", 0.5,
                  "Кафедра програмної інженерії", "Факультет інформатики", "Вступ до програмування", ""])

rooms = wb.create_sheet("Аудиторії")
rooms.append(["Корпус", "Поверх", "Номер", "Місткість", "Тип", "Кафедра"])
rooms.append(["А", 3, "305", 30, "лекційна", "Кафедра програмної інженерії"])
rooms.append(["А", 1, "101", 30, "комп'ютерний клас", "Кафедра програмної інженерії"])

groups = wb.create_sheet("Групи")
groups.append(["Факультет", "Спеціальність (код)", "Спеціальність (назва)", "Освітня програма",
                "Код групи", "Рік зарахування", "Чисельність"])
groups.append(["Факультет інформатики", "122", "Комп'ютерні науки", "", "КН-24-1", 2024, 25])

lessons = wb.create_sheet("Заняття")
lessons.append(["Дисципліна", "Викладач", "Група", "Тип заняття", "Тип розкладу",
                 "Пар на тиждень", "Тижні", "Тип аудиторії",
                 "Дата початку", "К-сть днів", "Пари", "Аудиторія", "Дати та пари"])
lessons.append(["Бази даних", "Коваленко Олена Іванівна", "КН-24-1", "лекція", "стрічковий",
                 1, "1-16", "", "", "", "", "", ""])
lessons.append(["Вступ до програмування", "Бондаренко Андрій Петрович", "КН-24-1", "практичне", "стрічковий",
                 2, "", "комп'ютерний клас", "", "", "", "", ""])
lessons.append(["Виробнича практика", "Коваленко Олена Іванівна", "КН-24-1", "практичне", "цикловий",
                 "", "", "", "2026-10-05", 5, "1,2,3", "А-305", ""])
lessons.append(["Настановча конференція", "Бондаренко Андрій Петрович", "КН-24-1", "консультація", "довільний",
                 "", "", "", "", "", "", "А-305", "02.09.2026:1; 15.12.2026:1"])

for ws in (settings, teachers, rooms, groups, lessons):
    for col in ws.columns:
        width = max(len(str(c.value)) if c.value is not None else 0 for c in col) + 2
        ws.column_dimensions[col[0].column_letter].width = min(max(width, 10), 40)
    for cell in ws[1]:
        cell.font = Font(bold=True)

wb.save("data_samples/sample.xlsx")
print("Записано data_samples/sample.xlsx")
